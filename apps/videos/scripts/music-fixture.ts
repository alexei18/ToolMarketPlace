/*
 * Test tracks with known beats and drops, into public/fixtures/ (not in git, never in a video that
 * ships). selftest.ts checks music:analyze against them; the test video plays one. No real track is
 * needed to prove the analysis, and none of these sound like music worth keeping.
 */
import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ensureDir, ROOT, writeWav } from "./lib/common";

const RATE = 44100;

export interface Fixture {
  name: string;
  bpm: number;
  /** Beats before the drop. */
  introBeats: number;
  totalBeats: number;
  /** A louder patch in the intro, to tempt the analysis into the wrong drop. */
  fakeBump?: boolean;
  /** Silence just before the drop, like a real break. */
  gap?: boolean;
  /** How far the beats wander, in seconds, as a loosely played track would. */
  jitter?: number;
  /** Gain of the section after the drop. */
  dropGain?: number;
  /** Bass and a kick already in the intro, as most real tracks have: the jump at the drop is small. */
  busyIntro?: boolean;
}

export const FIXTURES: Fixture[] = [
  { name: "test-drop", bpm: 124, introBeats: 16, totalBeats: 96, gap: true },
  { name: "test-slow", bpm: 92, introBeats: 12, totalBeats: 72, fakeBump: true },
  { name: "test-fast", bpm: 148, introBeats: 32, totalBeats: 140, gap: true, jitter: 0.008 },
  { name: "test-subtle", bpm: 110, introBeats: 16, totalBeats: 80, dropGain: 0.55 },
  { name: "test-busy", bpm: 128, introBeats: 32, totalBeats: 128, busyIntro: true, gap: true },
];

export function dropSeconds(f: Fixture): number {
  return (f.introBeats * 60) / f.bpm;
}

function rng(seed: number) {
  let s = seed >>> 0;
  return () => (s = (s * 1664525 + 1013904223) >>> 0) / 4294967296;
}

export function makeTrack(f: Fixture): { samples: Float32Array; beats: number[] } {
  const beat = 60 / f.bpm;
  const seconds = f.totalBeats * beat + 2;
  const x = new Float32Array(Math.round(seconds * RATE));
  const r = rng(f.bpm);
  const add = (at: number, secs: number, fn: (t: number) => number) => {
    const a = Math.round(at * RATE);
    const n = Math.round(secs * RATE);
    for (let i = 0; i < n && a + i < x.length; i++) x[a + i]! += fn(i / RATE);
  };
  const beats: number[] = [];
  const gain = f.dropGain ?? 1;
  for (let b = 0; b < f.totalBeats; b++) {
    const jitter = f.jitter ? (r() - 0.5) * 2 * f.jitter : 0;
    const t = b * beat + jitter;
    beats.push(t);
    const after = b >= f.introBeats;
    if (after) {
      // Kick, bass and a hat: what a drop brings.
      add(t, 0.35, (s) => gain * 0.9 * Math.sin(2 * Math.PI * (48 + 90 * Math.exp(-s * 34)) * s) * Math.exp(-s * 9));
      add(t, beat * 0.9, (s) => gain * 0.32 * Math.sin(2 * Math.PI * 55 * s) * Math.min(1, s * 60));
      add(t + beat / 2, 0.05, (s) => gain * 0.14 * (r() * 2 - 1) * Math.exp(-s * 90));
    } else {
      // A quiet pad and a soft tick, so the intro isn't silent.
      const inGap = f.gap && b >= f.introBeats - 1;
      if (!inGap) {
        add(t, 0.04, (s) => 0.05 * (r() * 2 - 1) * Math.exp(-s * 120));
        add(t, beat, (s) => 0.035 * Math.sin(2 * Math.PI * 330 * s));
      }
      if (f.busyIntro && !inGap) {
        add(t, 0.3, (s) => 0.3 * Math.sin(2 * Math.PI * (52 + 60 * Math.exp(-s * 34)) * s) * Math.exp(-s * 12));
        add(t, beat * 0.9, (s) => 0.09 * Math.sin(2 * Math.PI * 55 * s));
      }
      if (f.fakeBump && b >= 4 && b < 6) add(t, beat, (s) => 0.16 * Math.sin(2 * Math.PI * 660 * s));
    }
  }
  let peak = 0;
  for (const v of x) peak = Math.max(peak, Math.abs(v));
  for (let i = 0; i < x.length; i++) x[i]! *= 0.8 / peak;
  return { samples: x, beats };
}

export function writeFixtures(): string {
  const dir = path.join(ROOT, "public", "fixtures");
  ensureDir(dir);
  for (const f of FIXTURES) {
    // Seeded, so an existing file is already right; rewriting it would make every check that read it stale.
    const file = path.join(dir, `${f.name}.wav`);
    if (!existsSync(file)) writeWav(file, makeTrack(f).samples, RATE);
    writeFileSync(path.join(dir, `${f.name}.license.txt`), "Generated by scripts/music-fixture.ts. Test only, not for a posted video.\n");
  }
  return dir;
}

if (process.argv[1]?.endsWith("music-fixture.ts")) {
  console.log(`✔ ${FIXTURES.length} test tracks → ${writeFixtures()}`);
}
