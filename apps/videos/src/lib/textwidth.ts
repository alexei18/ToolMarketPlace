const FALLBACK = 560;

/** Width in px of a string in Inter Tight 800 at `size` px, with letter spacing in em (default -0.01em). */
export function textWidth(text: string, size: number, letterSpacingEm = -0.01): number {
  let units = 0;
  for (const ch of text) units += (WIDTH_PER_1000[ch] ?? FALLBACK) + letterSpacingEm * 1000;
  return (units * size) / 1000;
}
